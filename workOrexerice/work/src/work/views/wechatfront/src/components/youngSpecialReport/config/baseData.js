export const MakeHeightWeightP = (ageS, sexS, heightS, weightS) => {
    const age = Number(ageS)
    const sex = Number(sexS)
    const height = Number(heightS)
    const weight = Number(weightS)
    // console.log('AAAA1', age, sex, height, weight)


    let data
    if (sex === 2) {
        data = Woman
    } else {
        data = Man
    }
    const ageList = Object.keys(data).map(i => Number(i))
    let findAgeIndex = ageList.findIndex((item, index) => {
        if (age >= item && age < ageList[index + 1]) {
            return true
        } else {
            return false
        }
    })
    if (age >= 18) {
        findAgeIndex = ageList.findIndex(item => item === 18)
    }
    const heightWeightList = data[ageList[findAgeIndex].toString()]
    // console.log('AAAA2', heightWeightList)
    let pHeightIndex = null
    let pWeightIndex = null
    heightWeightList.forEach((item, index) => {
        const z0 = heightWeightList[index - 2] || -100
        const z1 = item
        const z2 = heightWeightList[index + 2] || 99999999
        const before = (z0 + z1) / 2
        const after = (z1 + z2) / 2
        if (index % 2 !== 0) {
            // 体重
            if (before <= weight && weight < after) {
                console.log('z0', z0, 'z1', z1, 'z2', z2, 'before', before, 'after', after)
                pWeightIndex = index
            }
        } else {
            // 身高
            if (item <= height && height < after) {
                pHeightIndex = index
            }
        }
    })
    if (weight <= heightWeightList[1]) {
        pWeightIndex = 1
    } else if (weight >= heightWeightList.slice(-1)[0]) {
        pWeightIndex = 13
    }
    if (height <= heightWeightList[0]) {
        pHeightIndex = 1
    } else if (height >= heightWeightList.slice(-2)[0]) {
        pHeightIndex = 12
    }
    // console.log('AAAA3', pHeightIndex, pWeightIndex)
    const h = Math.ceil((pHeightIndex + 1) / 2)
    const w = Math.ceil((pWeightIndex + 1) / 2)
    const P = [3, 10, 25, 50, 75, 90, 97]
    // console.log('BBB4', h, w, P)
    return [P[h - 1], P[w - 1]]
}



// 年龄、BMI
export const MakeBMIP = (ageS, sexS, bmiS) => {
    const age = Number(ageS)
    const sex = Number(sexS)
    const bmi = Number(bmiS)
    const ageList = Object.keys(BMI).map(i => Number(i))
    let findAgeIndex = ageList.findIndex((item, index) => {
        if (age >= item && age < ageList[index + 1]) {
            return true
        } else {
            return false
        }
    })
    if (age >= 18) {
        findAgeIndex = ageList.findIndex(item => item === 18)
    } else if (age <= 2) {
        findAgeIndex = ageList.findIndex(item => item === 2)
    }
    const BMIList = BMI[ageList[findAgeIndex].toString()]

    let value
    BMIList.forEach((item, index) => {
        const z0 = BMIList[index - 2] || -100
        const z1 = item
        const z2 = BMIList[index + 2] || 99999999
        const before = (z0 + z1) / 2
        const after = (z1 + z2) / 2
        if (index % 2 === 0 && sex === 1) {
            // 男
            if (before <= bmi && bmi < after) {
                value = index
            }
        } else if (index % 2 !== 0 && sex === 2) {
            // 女
            if (item <= bmi && bmi < BMIList[index + 2]) {
                value = index
            }
        }
    })
    if (sex === 1) {
        if (bmi <= BMIList[0]) {
            value = 1
        }
        if (bmi >= BMIList.slice(-2)[0]) {
            value = 16
        }
    } else {
        if (bmi <= BMIList[1]) {
            value = 1
        }
        if (bmi >= BMIList.slice(-1)[0]) {
            value = 17
        }
    }
    const b = Math.ceil((value + 1) / 2)
    const P = [3, 5, 10, 15, 50, 85, 90, 95, 97]
    return P[b - 1]
}